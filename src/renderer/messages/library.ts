export const libraryMessages: Catalog<typeof ko> = { ko, en }

/** Keys with a `.one` twin for the English singular. */
type CountedKey = {
  [Key in LibraryMessageKey]: `${Key}.one` extends LibraryMessageKey ? Key : never
}[LibraryMessageKey]

/** The key for `count` things: the `.one` twin when there is exactly one. */
export function countKey(key: CountedKey, count: number): LibraryMessageKey {
  return count === 1 ? (`${key}.one` as const) : key
}
